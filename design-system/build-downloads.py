def build_catalog(tok, css, comps):
    data = {
        "tokens": css,
        "bundleCss": read("components/bundle.css"),
        "bundleJs": read("components/bundle.js"),
        "readme": re.sub(r"^# DailyKit design system\n\n(>.*\n)+\n", "# DailyKit design system\n\n", read("README.md")),
        "colors": tok["color"]["tokens"],
        "components": comps,
    }
    payload = json.dumps(data, ensure_ascii=False).replace("</", "<\\/").replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
    page = (CATALOG.replace("__TOKENS__", css).replace("__BUNDLECSS__", data["bundleCss"]).replace("__DATA__", payload))
    write("catalog.html", page)


# ---------------------------------------------------------------- zips
def add(z, arcname, path=None, text=None):
    zi = zipfile.ZipInfo(arcname, STAMP)
    zi.compress_type = zipfile.ZIP_DEFLATED
    zi.external_attr = 0o644 << 16
    if text is None:
        with open(path, "rb") as f:
            z.writestr(zi, f.read())
    else:
        z.writestr(zi, text.encode("utf8"))


def walk(rel_dir, skip=()):
    base = os.path.join(HERE, rel_dir)
    for dp, dn, fn in os.walk(base):
        dn.sort()
        for f in sorted(fn):
            p = os.path.join(dp, f)
            rel = os.path.relpath(p, HERE).replace("\\", "/")
            if any(rel == s or rel.startswith(s.rstrip("/") + "/") for s in skip):
                continue
            yield rel, p


def make_zip(name, entries, prefix):
    p = os.path.join(OUT, name)
    with zipfile.ZipFile(p, "w") as z:
        for arc, path in entries:
            add(z, f"{prefix}/{arc}", path=path)
    return p


def build_zips(files_written):
    o = lambda rel: os.path.join(OUT, rel)
    h = lambda rel: os.path.join(HERE, rel)
    # 1 source: the design system as authored
    src = [(rel, p) for rel, p in walk(".", skip=("downloads",))]
    make_zip("dailykit-design-system-source.zip", src, "dailykit-design-system")
    # 2 tokens
    make_zip("dailykit-tokens.zip", [("tokens.json", h("tokens.json")), ("tokens.css", o("tokens.css"))], "dailykit-tokens")
    # 3 components: the runnable library and its types
    comp = [("bundle.js", h("components/bundle.js")), ("bundle.css", h("components/bundle.css")), ("index.d.ts", h("components/index.d.ts")),
            ("tokens.css", o("tokens.css")), ("catalog.html", o("catalog.html"))]
    p = os.path.join(OUT, "dailykit-components.zip")
    with zipfile.ZipFile(p, "w") as z:
        for arc, path in comp:
            add(z, "dailykit-components/" + arc, path=path)
        add(z, "dailykit-components/example.html", text=EXAMPLE)
    # 4 icons and logos as SVG
    ic = [(rel, o(rel)) for rel in files_written] + [(rel, p) for rel, p in walk("assets/Logos")]
    make_zip("dailykit-icons-and-logos-svg.zip", ic, "dailykit-icons-and-logos")
    # 4b the same logos as PNG, if they have been rendered (see README: a browser renders them from the SVGs)
    pngs = []
    pd = o("logos/png")
    if os.path.isdir(pd):
        pngs = [f"logos/png/{f}" for f in sorted(os.listdir(pd)) if f.endswith(".png")]
        make_zip("dailykit-logos-png.zip", [(rel, o(rel)) for rel in pngs], "dailykit-logos-png")
    # 5 everything
    allf = [(rel, p) for rel, p in walk(".", skip=("downloads",))]
    allf += [(f"downloads/{rel}", o(rel)) for rel in sorted(os.listdir(OUT)) if os.path.isfile(o(rel)) and not rel.endswith(".zip")]
    allf += [(f"downloads/{rel}", o(rel)) for rel in files_written + pngs]
    seen, uniq = set(), []
    for a, pth in allf:
        if a not in seen:
            seen.add(a); uniq.append((a, pth))
    make_zip("dailykit-design-system-complete.zip", uniq, "dailykit-design-system")



"""Build the downloadable versions of the DailyKit design system.

    python design-system/build-downloads.py

Reads this folder (tokens.json, components/, assets/) and writes design-system/downloads/:

    catalog.html                     one offline page: every component, live, in all four themes
    tokens.css, tokens.json          the tokens as CSS custom properties, and as data
    icons/ui/*.svg                   the eight UI icons (currentColor)
    icons/games/*.svg                each game's mark, light and dark accent
    logos/*.svg                      each game's badge and badge + wordmark lockup, light and dark
    dailykit-*.zip                   the same, packaged (fixed timestamps: a rebuild is byte-stable)

Standard library plus Node (only to read the icon and game tables out of components/bundle.js).
"""
import json, os, re, subprocess, sys, zipfile, html

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "downloads")
STAMP = (2026, 9, 21, 0, 0, 0)


def read(p):
    with open(os.path.join(HERE, p), encoding="utf8", newline="") as f:
        return f.read().replace("\r\n", "\n")


def write(rel, text):
    p = os.path.join(OUT, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", encoding="utf8", newline="\n") as f:
        f.write(text)


# ---------------------------------------------------------------- tokens.css
def tokens_css(tok):
    themes = [t["id"] for t in tok["color"]["themes"]]
    first = themes[0]

    def val(t, th):
        v = t["value"]
        if isinstance(v, str):
            return v
        return v.get(th, v.get(first))

    def alias(v):
        m = re.fullmatch(r"\{(.+)\}", v)
        return f"var(--{m.group(1)})" if m else v

    out = ["/* DailyKit design tokens. Generated by build-downloads.py from tokens.json: do not edit. */"]
    for i, th in enumerate(themes):
        sel = f':root, [data-theme="{th}"]' if th == first else f'[data-theme="{th}"]'
        lines = [f"  --{t['name']}: {alias(val(t, th))};" for t in tok["color"]["tokens"]]
        for t in tok.get("shadow", {}).get("tokens", []):
            lines.append(f"  --{t['name']}: {val(t, th)};")
        out.append(sel + " {\n" + "\n".join(lines) + "\n}")
    root = []
    for fam in ("spacing", "radius"):
        for t in tok.get(fam, {}).get("tokens", []):
            root.append(f"  --{t['name']}: {t['value']};")
    for k, v in tok["type"]["families"].items():
        root.append(f"  --font-{k}: {v};")
    out.append(":root {\n" + "\n".join(root) + "\n}")
    for g in tok["type"]["groups"]:
        for s in g["styles"]:
            fam = s.get("family") or g["family"]
            decl = [f"font-family: var(--font-{fam})", f"font-size: {s['fontSize']}", f"line-height: {s['lineHeight']}",
                    f"font-weight: {s['fontWeight']}"]
            if s.get("letterSpacing") not in (None, "", "0"):
                decl.append(f"letter-spacing: {s['letterSpacing']}")
            out.append(f".{s['name']} {{ " + "; ".join(decl) + "; }")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- bundle tables via node
def bundle_tables():
    js = os.path.join(HERE, "components", "bundle.js").replace("\\", "/")
    code = ("global.window={};eval(require('fs').readFileSync(%s,'utf8'));"
            "const K=window.DailyKit;console.log(JSON.stringify({games:K.GAMES,icons:K.ICONS,labels:K.ICON_LABEL}))" % json.dumps(js))
    r = subprocess.run(["node", "-e", code], capture_output=True, text=True, encoding="utf8", check=True)
    return json.loads(r.stdout)


# ---------------------------------------------------------------- svg files
def hsl(h, s, l):
    return f"hsl({h} {s}% {l}%)"


def hue_of(game):
    return int(re.search(r"hsl\((\d+)", game["accent_light"]).group(1))


def svg_wrap(inner, size, color, extra=""):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="{size}" height="{size}" '
            f'color="{color}"{extra}>{inner}</svg>\n')


def build_svgs(tok, tables):
    tokens = {t["name"]: t for t in tok["color"]["tokens"]}
    files = []
    for name, inner in tables["icons"].items():
        rel = f"icons/ui/{name}.svg"
        write(rel, svg_wrap(inner, 24, "hsl(0 0% 12%)", f' role="img" aria-label="{html.escape(tables["labels"][name])}"'))
        files.append(rel)
    for g in tables["games"]:
        t = tokens["game-" + g["id"]]["value"]
        light, dark = t["light"], t["dark"]
        h = int(re.search(r"hsl\((\d+)", light).group(1))
        on_light = "hsl(0 0% 12%)" if g.get("on") == "dark" else "hsl(0 0% 100%)"
        on_dark = "hsl(220 12% 10%)"
        name = g["name"]
        for variant, accent, text, icon_on in (("light", light, "hsl(0 0% 12%)", on_light), ("dark", dark, "hsl(0 0% 94%)", on_dark)):
            # the mark alone, in the accent
            rel = f"icons/games/{g['id']}-{variant}.svg"
            write(rel, svg_wrap(g["icon"], 96, accent, f' role="img" aria-label="{html.escape(name)}"'))
            files.append(rel)
            # the badge: accent square holding the mark
            badge = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="256" height="256" role="img" aria-label="{html.escape(name)}">'
                     f'<rect width="64" height="64" rx="12" fill="{accent}"/>'
                     f'<g transform="translate(14 14) scale(1.5)" color="{icon_on}">{g["icon"]}</g></svg>\n')
            rel = f"logos/{g['id']}-badge-{variant}.svg"
            write(rel, badge)
            files.append(rel)
            # the lockup: badge + name, transparent background
            width = 80 + int(len(name) * 21) + 8
            lock = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} 64" width="{width}" height="64" role="img" aria-label="{html.escape(name)}">'
                    f'<rect width="64" height="64" rx="12" fill="{accent}"/>'
                    f'<g transform="translate(14 14) scale(1.5)" color="{icon_on}">{g["icon"]}</g>'
                    f'<text x="80" y="43" font-family="system-ui, -apple-system, \'Segoe UI\', Roboto, \'Helvetica Neue\', Arial, sans-serif" '
                    f'font-size="28" font-weight="700" letter-spacing="1.1" fill="{text}">{html.escape(name)}</text></svg>\n')
            rel = f"logos/{g['id']}-lockup-{variant}.svg"
            write(rel, lock)
            files.append(rel)
    return files


# ---------------------------------------------------------------- catalog.html
def components():
    out = []
    root = os.path.join(HERE, "components")
    for name in sorted(os.listdir(root)):
        d = os.path.join(root, name)
        pv = os.path.join(d, "preview.html")
        if not os.path.isfile(pv):
            continue
        prev = read(f"components/{name}/preview.html")
        m = re.match(r"<!--\s*@dsCard\s+([^>]*?)-->", prev)
        attrs = dict(re.findall(r'(\w+)=("[^"]*"|\d+)', m.group(1))) if m else {}
        group = attrs.get("group", "").strip('"') or "Other"
        height = int(attrs.get("height", "160").strip('"'))
        rd = f"components/{name}/README.md"
        out.append({"name": name, "group": group, "height": height, "preview": prev,
                    "readme": read(rd) if os.path.isfile(os.path.join(HERE, rd)) else ""})
    return out


